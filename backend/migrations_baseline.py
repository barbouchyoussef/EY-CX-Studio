"""Fast-path a brand-new database from a schema baseline instead of replaying every migration.

Replaying the numbered migrations onto an empty database works -- that is verified -- but it is
not how anyone should have to LEARN the schema. The current shape is spread across 59 files and
includes churn: columns added then altered, a constraint cleanup pass, tables renamed. A newcomer
who wants to know what `assessments` looks like today should read one file, not replay history in
their head.

`migrations/baseline/schema.sql` is a dump of exactly the state those migrations produce. It was
generated by replaying all of them onto an empty Postgres and dumping the result, then checked
against that same replay:

  * schema dumps identical apart from two CHECK constraints that Postgres re-renders after a
    dump/restore round-trip (`ARRAY[...]::text[]` becomes `ARRAY[...::text, ...]`). Both
    renderings were tested and enforce the same thing -- valid values accepted, invalid rejected.
  * all seven reference tables byte-identical by checksum.

Only a genuinely EMPTY database takes this path. Anything with existing tables keeps replaying
migrations one at a time from wherever it left off, so production is untouched by this.

Rebuilding the baseline after adding migrations (not automated on purpose -- it needs a throwaway
Postgres, and a stale baseline is worse than none):

    docker run -d --name tmp-pg -e POSTGRES_PASSWORD=t -e POSTGRES_DB=b -p 55441:5432 postgres:16
    DATABASE_URL=postgresql://postgres:t@127.0.0.1:55441/b python seed.py
    docker exec tmp-pg pg_dump -U postgres -d b --schema-only --no-owner --no-privileges \\
        --no-comments > migrations/baseline/schema.sql
    docker exec tmp-pg pg_dump -U postgres -d b --data-only --no-owner --no-privileges \\
        -t axes -t capabilities -t capability_maturity_rubrics -t company_sizes \\
        -t maturity_levels -t regions -t sectors >> migrations/baseline/schema.sql
    docker rm -f tmp-pg
"""

from pathlib import Path

BASELINE_PATH = Path(__file__).resolve().parent / "migrations" / "baseline" / "schema.sql"

# Tables whose contents are reference data the app needs in order to work at all -- the maturity
# framework, the sector list. A database with the schema but not these is not actually usable.
SEEDED_TABLES = (
    "axes", "capabilities", "capability_maturity_rubrics", "company_sizes",
    "maturity_levels", "regions", "sectors",
)


def database_is_empty(conn) -> bool:
    """True when the database holds no application tables yet.

    `migration_history` does not count as content: it is bookkeeping, and a database carrying
    only that is still fresh.
    """
    with conn.cursor() as cur:
        cur.execute(
            "SELECT count(*) FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name <> 'migration_history';"
        )
        return cur.fetchone()[0] == 0


def read_baseline() -> str | None:
    """The baseline SQL with psql meta-commands stripped, or None if there is no baseline.

    pg_dump 16 wraps its output in `\\restrict` / `\\unrestrict` lines. Those are psql client
    directives rather than SQL, and psycopg2 raises a syntax error on them. They are filtered
    here instead of being edited out of the file, so the file stays a faithful dump that can be
    diffed against a fresh one.
    """
    if not BASELINE_PATH.exists():
        return None
    lines = BASELINE_PATH.read_text(encoding="utf-8").splitlines()
    return "\n".join(line for line in lines if not line.startswith("\\"))


def apply_baseline(conn, sql_files) -> bool:
    """Create the schema in one step and record every migration as already applied.

    Returns False when there is no baseline file, so the caller can fall back to replaying.
    Recording the full history matters: without it the next `python seed.py` would try to apply
    all 59 files on top of a schema that already has them.
    """
    sql = read_baseline()
    if sql is None:
        return False

    print(f"Empty database detected. Applying schema baseline instead of replaying "
          f"{len(sql_files)} migrations.")
    with conn.cursor() as cur:
        cur.execute(sql)
        # pg_dump blanks the session search_path (`set_config('search_path', '', false)`) so its
        # own statements are unambiguous. That persists on this connection, so restore it before
        # anything unqualified runs -- and qualify the insert below regardless.
        cur.execute("SET search_path TO public;")
        for sql_file in sql_files:
            cur.execute(
                "INSERT INTO public.migration_history (filename) VALUES (%s) "
                "ON CONFLICT DO NOTHING;",
                (sql_file.name,),
            )
    conn.commit()
    print(f"Baseline applied; {len(sql_files)} migrations recorded as already present.")
    return True

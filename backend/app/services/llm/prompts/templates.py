"""Every prompt the maturity assessment sends, in one place.

Grouped by the stage that uses them: intent routing, question generation, clarification, coverage
scoring, company classification, recommendations, and report synthesis. Keeping them together
means a wording change is reviewable as a diff in one file rather than hunted across services.

`language_directive` is prepended by callers to force the response language. That mattering is
not theoretical -- a language instruction that failed to reach a sub-call is what produced
mixed-language reports.

**A duplication was removed here, and the reason is worth knowing.** This file used to define
eight of these constants twice, the second copy silently overwriting the first. Seven copies were
identical, so they were merely noise. The eighth was not: the first `REPORT_SYNTHESIS_SYSTEM_PROMPT`
held *question-generation* instructions -- it told the model to write a consultative question and
return `{"question": ..., "options": [...]}`. Report synthesis worked only because the correct
version was assigned 195 lines further down and won. Deleting the dead first block was verified as
a no-op by hashing every exported prompt before and after; all fifteen were byte-identical.
"""

def language_directive(lang: str) -> str:
    names = {"fr": "French", "en": "English"}
    name = names.get(lang, "English")
    if name == "French":
        return (
            "\nCRITICAL LANGUAGE CONSTRAINT:\n"
            "You MUST speak, write, and respond strictly and entirely in French.\n"
            "All questions, follow-ups, multi-choice options, executive summaries, priority messages, recommendations, titles, and report text MUST be in French.\n"
            "Never output English. If input contains English, translate it to French in your response."
        )
    else:
        return (
            "\nCRITICAL LANGUAGE CONSTRAINT:\n"
            "You MUST speak, write, and respond strictly and entirely in English.\n"
            "All questions, follow-ups, multi-choice options, executive summaries, priority messages, recommendations, titles, and report text MUST be in English.\n"
            "Never output French."
        )



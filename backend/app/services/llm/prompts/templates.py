        persona_block = (
            f"\n═══ THEMATIC AREAS — {profile.upper()} ═══\n"
            f"Angle: Custom Stakeholder Role Audit\n"
            f"Role Specifications and Persona Details:\n"
            f"{custom_profile_description}\n"
        )
